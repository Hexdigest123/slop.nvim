local h = require("helpers")

describe("util", function()
  local util
  before_each(function()
    h.reset()
    util = require("slop.core.util")
  end)

  it("debounce keeps the last call and supports cancel/flush", function()
    local calls = {}
    local d = util.debounce(function(x)
      calls[#calls + 1] = x
    end, 20)
    d(1)
    d(2)
    d(3)
    vim.wait(200, function()
      return #calls > 0
    end)
    assert.are.same({ 3 }, calls)
    d(4)
    d:cancel()
    vim.wait(60)
    assert.are.same({ 3 }, calls)
    d(5)
    assert.is_true(d:pending())
    d:flush()
    assert.are.same({ 3, 5 }, calls)
    d:close()
  end)

  it("table helpers", function()
    local t = {}
    util.tbl_set(t, "a.b.c", 1)
    assert.equal(1, util.tbl_get(t, "a.b.c"))
    assert.equal(1, util.tbl_get(t, "a", "b", "c"))
    assert.is_nil(util.tbl_get(t, "a.x.c"))
    assert.are.same({ "ab", "ac" }, util.complete_prefix({ "ac", "b", "ab" }, "a"))
    assert.are.same({ 1, 2 }, util.uniq({ 1, 2, 1 }))
    assert.are.same(
      { a = { b = 2, c = 1 }, l = { 9 } },
      util.merge({ a = { c = 1 }, l = { 1, 2 } }, { a = { b = 2 }, l = { 9 } })
    )
  end)

  it("region marks track edits; tick_guard detects changes", function()
    local buf = vim.api.nvim_create_buf(false, true)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "a", "b", "c", "d" })
    local ns = util.ns("test")
    local id = util.region_mark(buf, ns, { 1, 0, 2, 1 })
    local guard = util.tick_guard(buf)
    assert.is_true(guard())
    vim.api.nvim_buf_set_lines(buf, 0, 0, false, { "new" })
    assert.is_false(guard())
    assert.are.same({ 2, 0, 3, 1 }, util.mark_range(buf, ns, id))
    assert.are.same({ "b", "c" }, util.range_text(buf, util.mark_range(buf, ns, id)))
    assert.is_true(util.mark_valid(buf, ns, id))
    vim.api.nvim_buf_del_extmark(buf, ns, id)
    assert.is_false(util.mark_valid(buf, ns, id))
  end)

  it("hl() defines default links that survive :colorscheme", function()
    util.hl({ SlopTestThing = { link = "Title" } })
    assert.equal("Title", vim.api.nvim_get_hl(0, { name = "SlopTestThing" }).link)
    h.source_plugin()
    vim.cmd("hi clear")
    vim.api.nvim_exec_autocmds("ColorScheme", {})
    assert.equal("Title", vim.api.nvim_get_hl(0, { name = "SlopTestThing" }).link)
    assert.equal("FloatBorder", vim.api.nvim_get_hl(0, { name = "SlopBorder" }).link)
  end)

  it("augroup() is named slop.<module> and not cleared by default", function()
    local g = util.augroup("x")
    vim.api.nvim_create_autocmd("User", { group = g, pattern = "Nope", callback = function() end })
    util.augroup("x")
    assert.equal(1, #vim.api.nvim_get_autocmds({ group = "slop.x" }))
  end)
end)
