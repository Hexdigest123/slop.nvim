local h = require("helpers")

describe("project", function()
  local project, root
  before_each(function()
    h.reset()
    project = require("slop.core.project")
    root = h.tmpdir("proj")
    vim.fn.mkdir(root .. "/.git", "p")
    vim.fn.mkdir(root .. "/src/deep", "p")
  end)

  it("finds the root from a buffer path via markers", function()
    h.write(root .. "/src/deep/file.lua", "x")
    vim.cmd.edit(root .. "/src/deep/file.lua")
    assert.equal(root, project.root())
    assert.equal(root, project.root(0))
  end)

  it("falls back to cwd for unnamed buffers / no markers", function()
    local plain = h.tmpdir("plain")
    vim.cmd.cd(plain)
    vim.cmd.enew()
    assert.equal(plain, project.root())
    vim.cmd.cd(root .. "/src")
    assert.equal(root, project.root())
  end)

  it("honours custom root markers", function()
    require("slop.config").setup({ project = { root_markers = { "marker.txt" } } })
    h.write(root .. "/src/marker.txt", "")
    h.write(root .. "/src/deep/a.lua", "")
    vim.cmd.edit(root .. "/src/deep/a.lua")
    assert.equal(root .. "/src", project.root())
  end)

  it("dir() and file() resolve inside <root>/.nvim", function()
    assert.equal(root .. "/.nvim/commit.md", project.dir({ root = root }, "commit.md"))
    assert.is_nil(project.file("commit.md", { root = root }))
    h.write(root .. "/.nvim/commit.md", "rules")
    assert.equal(root .. "/.nvim/commit.md", project.file("commit.md", { root = root }))
  end)

  it("state() creates dirs lazily and writes .nvim/.gitignore once", function()
    local p = project.state("rest", "cookies.txt", { root = root })
    assert.equal(root .. "/.nvim/state/rest/cookies.txt", p)
    assert.truthy(vim.uv.fs_stat(root .. "/.nvim/state/rest"))
    assert.is_nil(vim.uv.fs_stat(p), "file itself is not created")
    assert.equal("state/\n", h.read(root .. "/.nvim/.gitignore"))
    project.state("term", nil, { root = root })
    assert.equal("state/\n", h.read(root .. "/.nvim/.gitignore"))
  end)

  it("state() appends state/ to an existing .nvim/.gitignore", function()
    h.write(root .. "/.nvim/.gitignore", "secret.md")
    project.state("x", nil, { root = root })
    assert.equal("secret.md\nstate/\n", h.read(root .. "/.nvim/.gitignore"))
  end)

  it("write_json/read_json round-trip atomically", function()
    local p = project.state("rest", "history.json", { root = root })
    assert.is_true(project.write_json(p, { b = { 1, 2 }, a = "x" }))
    assert.are.same({ a = "x", b = { 1, 2 } }, project.read_json(p))
    assert.is_true(project.write_json(p, { v = 2 }))
    assert.are.same({ v = 2 }, project.read_json(p))
    local leftovers = vim.fn.glob(p .. ".tmp.*", false, true)
    assert.are.same({}, leftovers)
  end)

  it("read_json reports missing and invalid files", function()
    local data, err = project.read_json(root .. "/nope.json")
    assert.is_nil(data)
    assert.truthy(err)
    h.write(root .. "/bad.json", "{nope")
    data, err = project.read_json(root .. "/bad.json")
    assert.is_nil(data)
    assert.matches("invalid json", err)
  end)

  it("write_file creates parent directories", function()
    assert.is_true(project.write_file(root .. "/a/b/c.txt", "hi"))
    assert.equal("hi", h.read(root .. "/a/b/c.txt"))
  end)
end)
